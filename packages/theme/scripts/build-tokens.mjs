#!/usr/bin/env node
/**
 * 设计令牌构建脚本
 * 读取 packages/theme/src/tokens.ts（唯一事实来源），生成：
 *   1. packages/theme/src/tokens.json
 *   2. apps/web/src/styles/tokens.css
 * 用法：node packages/theme/scripts/build-tokens.mjs
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');
const src = resolve(root, 'packages/theme/src/tokens.ts');
const source = readFileSync(src, 'utf8');

/** 极简解析：取出 `export const <name> = { ... } as const;` 的顶层块 */
function extractBlock(name) {
  const marker = `export const ${name} = {`;
  const start = source.indexOf(marker);
  if (start < 0) throw new Error(`token block not found: ${name}`);
  let i = source.indexOf('{', start);
  let depth = 0;
  for (let j = i; j < source.length; j += 1) {
    const ch = source[j];
    if (ch === '{') depth += 1;
    else if (ch === '}') {
      depth -= 1;
      if (depth === 0) return source.slice(i, j + 1);
    }
  }
  throw new Error(`unbalanced block: ${name}`);
}

/** 把 TS 对象字面量转成可求值的 JS（去注释、把多余逗号交给 eval 处理） */
function evalBlock(block) {
  const cleaned = block
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\/\/.*$/gm, '');
  // eslint-disable-next-line no-new-func
  return new Function(`return (${cleaned});`)();
}

const names = ['color', 'radius', 'fontSize', 'spacing', 'boxShadow', 'easing', 'animation', 'keyframes', 'fontFamily'];
const out = {};
for (const n of names) out[n] = evalBlock(extractBlock(n));

/* ---------- 1. tokens.json ---------- */
writeFileSync(
  resolve(root, 'packages/theme/src/tokens.json'),
  JSON.stringify(out, null, 2) + '\n',
  'utf8',
);

/* ---------- 2. tokens.css ---------- */
const hslTriplet = (value) => {
  const m = /^hsl\(([\d.]+)\s+([\d.]+)%\s+([\d.]+)%\)$/.exec(value);
  if (m) return `${m[1]} ${m[2]}% ${m[3]}%`;
  const m2 = /^hsla?\(([^)]+)\)$/.exec(value);
  return m2 ? m2[1].trim() : value;
};

const lines = [];
lines.push('/* AUTO-GENERATED by packages/theme/scripts/build-tokens.mjs — 请勿手工修改 */');
lines.push('/* 毛绒实木 (Plush x Birch Wood) 设计令牌 */');
lines.push(':root {');

lines.push('  /* ---- 色彩：同时输出 hsl 三元组，便于 hsl(var(--x) / <alpha>) ---- */');
for (const [k, v] of Object.entries(out.color)) {
  lines.push(`  --color-${k}: ${hslTriplet(v)}; /* ${v} */`);
}

lines.push('');
lines.push('  /* ---- 圆角 ---- */');
for (const [k, v] of Object.entries(out.radius)) lines.push(`  --radius-${k}: ${v};`);

lines.push('');
lines.push('  /* ---- 间距 ---- */');
for (const [k, v] of Object.entries(out.spacing)) lines.push(`  --space-${k}: ${v};`);

lines.push('');
lines.push('  /* ---- 字号 / 行高 ---- */');
for (const [k, v] of Object.entries(out.fontSize)) {
  lines.push(`  --text-${k}: ${v[0]};`);
  lines.push(`  --text-${k}--line-height: ${v[1].lineHeight};`);
  if (v[1].letterSpacing) lines.push(`  --text-${k}--letter-spacing: ${v[1].letterSpacing};`);
}

lines.push('');
lines.push('  /* ---- 毛绒软阴影 ---- */');
for (const [k, v] of Object.entries(out.boxShadow)) lines.push(`  --shadow-${k}: ${v};`);

lines.push('');
lines.push('  /* ---- 动效 ---- */');
for (const [k, v] of Object.entries(out.easing)) lines.push(`  --ease-${k}: ${v};`);
for (const [k, v] of Object.entries(out.animation)) lines.push(`  --animate-${k}: ${v};`);

lines.push('');
lines.push('  /* ---- 字体 ---- */');
lines.push(`  --font-en: ${out.fontFamily.en.map((f) => (f.includes(' ') ? `"${f}"` : f)).join(', ')};`);
lines.push(`  --font-zh: ${out.fontFamily.zh.map((f) => (f.includes(' ') || /^[A-Z]/.test(f) ? `"${f}"` : f)).join(', ')};`);
lines.push('}');

lines.push('');
lines.push('/* ---- keyframes（呼吸感动效） ---- */');
for (const [name, frames] of Object.entries(out.keyframes)) {
  lines.push(`@keyframes ${name} {`);
  for (const [stop, decl] of Object.entries(frames)) {
    lines.push(`  ${stop} {`);
    for (const [p, v] of Object.entries(decl)) {
      const cssProp = p.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
      lines.push(`    ${cssProp}: ${v};`);
    }
    lines.push('  }');
  }
  lines.push('}');
}
lines.push('');
lines.push('/* 尊重系统「减少动态效果」设置 */');
lines.push('@media (prefers-reduced-motion: reduce) {');
lines.push('  *, *::before, *::after {');
lines.push('    animation-duration: 0.001ms !important;');
lines.push('    animation-iteration-count: 1 !important;');
lines.push('    transition-duration: 0.001ms !important;');
lines.push('  }');
lines.push('}');
lines.push('');

const cssTarget = resolve(root, 'apps/web/src/styles/tokens.css');
if (!existsSync(dirname(cssTarget))) mkdirSync(dirname(cssTarget), { recursive: true });
writeFileSync(cssTarget, lines.join('\n'), 'utf8');

console.log(`✓ packages/theme/src/tokens.json`);
console.log(`✓ apps/web/src/styles/tokens.css`);
console.log(`  tokens: ${Object.keys(out.color).length} colors, ${Object.keys(out.animation).length} animations`);
